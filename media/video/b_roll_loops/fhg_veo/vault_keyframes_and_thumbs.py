def extract_frame(video_path: Path, time_s: float, out_jpg: Path) -> None:
    subprocess.run(
        [
            "ffmpeg", "-y", "-ss", f"{time_s:.2f}",
            "-i", str(video_path),
            "-frames:v", "1", "-q:v", "2",
            str(out_jpg),
        ],
        check=True,
        capture_output=True,
    )


def build_thumbnail_16x9(bg_jpg: Path, badge_text: str, line1: str, line2: str, out_jpg: Path) -> None:
    img = Image.open(bg_jpg).convert("RGB").resize((1280, 720), Image.Resampling.LANCZOS)
    # Darken left/bottom slightly for crisp typography contrast
    overlay = Image.new("RGBA", (1280, 720), (0, 0, 0, 0))
    draw_ov = ImageDraw.Draw(overlay)
    for y in range(720):
        if y < 320:
            alpha = 0
        else:
            alpha = int(205 * ((y - 320) / 400.0) ** 1.4)
        draw_ov.line([(0, y), (1280, y)], fill=(14, 10, 7, min(210, alpha)))
    img = Image.alpha_composite(img.convert("RGBA"), overlay).convert("RGB")

    draw = ImageDraw.Draw(img)
    font_bold = str(FONTS_DIR / "Montserrat-Black.ttf")
    f_badge = ImageFont.truetype(font_bold, 24)
    f_l1 = ImageFont.truetype(font_bold, 58)
    f_l2 = ImageFont.truetype(font_bold, 64)

    # Gold pill badge
    draw.rounded_rectangle([54, 430, 520, 476], radius=10, fill=(200, 138, 30))
    draw.text((72, 440), badge_text, font=f_badge, fill=(255, 255, 245))

    # Main lines with shadow
    draw.text((58, 496), line1, font=f_l1, fill=(0, 0, 0))
    draw.text((54, 492), line1, font=f_l1, fill=(255, 255, 240))

    draw.text((58, 566), line2, font=f_l2, fill=(0, 0, 0))
    draw.text((54, 562), line2, font=f_l2, fill=(255, 191, 0))

    img.save(out_jpg, quality=95)


